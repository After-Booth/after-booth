CREATE TABLE member (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email_normalized varchar(254) UNIQUE,
  password_hash text,
  state text NOT NULL CHECK (state IN ('PENDING_VERIFICATION', 'ACTIVE', 'WITHDRAWN')),
  auth_version bigint NOT NULL DEFAULT 0 CHECK (auth_version >= 0),
  created_at timestamptz NOT NULL,
  verified_at timestamptz,
  withdrawn_at timestamptz,
  purge_after timestamptz,
  CHECK ((state = 'WITHDRAWN' AND email_normalized IS NULL AND password_hash IS NULL
      AND withdrawn_at IS NOT NULL AND purge_after IS NOT NULL AND purge_after = withdrawn_at + interval '720 hours')
    OR (state <> 'WITHDRAWN' AND email_normalized IS NOT NULL AND password_hash IS NOT NULL
      AND withdrawn_at IS NULL AND purge_after IS NULL)),
  CHECK (state <> 'ACTIVE' OR verified_at IS NOT NULL)
);

CREATE TABLE withdrawn_email_block (
  email_hmac bytea NOT NULL,
  key_version text NOT NULL,
  blocked_until timestamptz NOT NULL,
  PRIMARY KEY (key_version, email_hmac)
);

CREATE TABLE refresh_session (
  id uuid PRIMARY KEY,
  member_id bigint NOT NULL REFERENCES member(id),
  auth_version bigint NOT NULL,
  created_at timestamptz NOT NULL,
  expires_at timestamptz NOT NULL,
  revoked_at timestamptz,
  CHECK (expires_at = created_at + interval '168 hours')
);

CREATE TABLE refresh_token (
  token_hash bytea PRIMARY KEY,
  session_id uuid NOT NULL REFERENCES refresh_session(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL,
  used_at timestamptz
);
CREATE UNIQUE INDEX refresh_token_one_unused_per_session ON refresh_token(session_id) WHERE used_at IS NULL;

CREATE TABLE auth_challenge (
  id text PRIMARY KEY,
  member_id bigint REFERENCES member(id),
  email_key bytea NOT NULL,
  key_version text NOT NULL,
  purpose text NOT NULL CHECK (purpose IN ('SIGNUP_VERIFY', 'PASSWORD_RESET')),
  code_hmac bytea,
  attempts int NOT NULL DEFAULT 0 CHECK (attempts BETWEEN 0 AND 5),
  created_at timestamptz NOT NULL,
  expires_at timestamptz NOT NULL,
  consumed_at timestamptz,
  CHECK ((member_id IS NULL) = (code_hmac IS NULL)),
  CHECK (expires_at = created_at + interval '10 minutes')
);
CREATE INDEX auth_challenge_email_purpose ON auth_challenge(key_version, email_key, purpose);
CREATE INDEX auth_challenge_expiry ON auth_challenge(expires_at);

CREATE TABLE csrf_session (
  id_hash bytea PRIMARY KEY,
  token_hash bytea NOT NULL,
  member_id bigint REFERENCES member(id),
  created_at timestamptz NOT NULL,
  expires_at timestamptz NOT NULL,
  CHECK (expires_at = created_at + interval '1 hour')
);

CREATE TABLE auth_rate_limit (
  scope text NOT NULL,
  subject_hmac bytea NOT NULL,
  key_version text NOT NULL,
  window_start timestamptz NOT NULL,
  count int NOT NULL CHECK (count >= 0),
  expires_at timestamptz NOT NULL,
  PRIMARY KEY (scope, subject_hmac, key_version, window_start),
  CHECK (expires_at > window_start)
);

CREATE TABLE reuse_archive (
  event_id bigint NOT NULL REFERENCES event(id),
  category text NOT NULL CHECK (category IN ('DISPLAY_RACK', 'STORAGE_BIN', 'FOLDING_TABLE')),
  reused_qty bigint NOT NULL CHECK (reused_qty >= 0),
  reused_volume_cm3 numeric(38,0) NOT NULL CHECK (reused_volume_cm3 >= 0),
  PRIMARY KEY (event_id, category)
);

